    float interpolate(const std::vector<float>& e, const std::vector<float>& mu, float e_kev)
    {
        e_kev = std::clamp(e_kev, e.front(), e.back());
        const size_t hi = std::min<size_t>(std::upper_bound(e.begin(), e.end(), e_kev) - e.begin(), e.size() - 1);
        const size_t lo = (hi > 0) ? hi - 1 : 0;
        if (hi == lo || e[hi] == e[lo])
            return mu[lo];
        const float t = (std::log(e_kev) - std::log(e[lo])) / (std::log(e[hi]) - std::log(e[lo]));
        return std::exp(std::log(mu[lo]) + t * (std::log(mu[hi]) - std::log(mu[lo])));
    }

