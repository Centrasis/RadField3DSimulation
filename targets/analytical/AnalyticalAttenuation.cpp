bool AttenuationTable::has_table(const std::string& material)
{
    return material == "CsI" || material == "G4_WATER";
}

float AttenuationTable::mass_attenuation(const std::string& material, float e_kev)
{
    if (material == "CsI")
        return interpolate(csi_e, csi_mu, e_kev);
    if (material == "G4_WATER")
        return interpolate(water_e, water_mu, e_kev);
    throw std::invalid_argument("no mass attenuation table for material "" + material + """);
}

std::vector<float> AttenuationTable::optical_thickness(const std::string& material, float density_g_cm3, float thickness_m,
                                                       int bins, float bin_width_ev)
{
    // Water-like fallback for materials without a table: the water table scaled by density.
    const std::string table_material = has_table(material) ? material : "G4_WATER";
    const float areal_density = density_g_cm3 * thickness_m * 100.f;   // g/cm^2
    constexpr int sub_samples = 32;
    std::vector<float> tau(bins);
    for (int b = 0; b < bins; ++b) {
        // transmission averaged over the bin (an absorption edge inside the bin makes the bin-centre value wrong), as an
        // optical thickness
        double transmitted = 0.0;
        for (int s = 0; s < sub_samples; ++s) {
            const float e_kev = (b + (s + 0.5f) / sub_samples) * bin_width_ev / 1000.f;
            transmitted += std::exp(-mass_attenuation(table_material, e_kev) * areal_density);
        }
        tau[b] = static_cast<float>(-std::log(std::max(transmitted / sub_samples, 1e-30)));
    }
    return tau;
}
